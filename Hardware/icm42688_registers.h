#ifndef ICM42688_REGISTERS_H
#define ICM42688_REGISTERS_H

#include "Config/imu_config.h"

/* TDK InvenSense DS-000347, ICM-42688-P Datasheet, Revision 1.9. */
#define ICM42688_REG_DEVICE_CONFIG  0x11U
#define ICM42688_REG_ACCEL_DATA_X1  0x1FU
#define ICM42688_REG_PWR_MGMT0      0x4EU
#define ICM42688_REG_GYRO_CONFIG0   0x4FU
#define ICM42688_REG_ACCEL_CONFIG0  0x50U
#define ICM42688_REG_WHO_AM_I       0x75U

#define ICM42688_WHO_AM_I_VALUE     0x47U
#define ICM42688_SPI_READ_BIT       0x80U

#define ICM42688_DEVICE_SOFT_RESET  0x01U

#define ICM42688_GYRO_CONFIG_VALUE  ((ICM42688_GYRO_FS_SELECT << 5) | ICM42688_ODR_SELECT)
#define ICM42688_ACCEL_CONFIG_VALUE ((ICM42688_ACCEL_FS_SELECT << 5) | ICM42688_ODR_SELECT)

#define ICM42688_GYRO_MODE_LN       (3U << 2)
#define ICM42688_ACCEL_MODE_LN      3U
#define ICM42688_PWR_MGMT0_LN_VALUE (ICM42688_GYRO_MODE_LN | ICM42688_ACCEL_MODE_LN)

#define ICM42688_SAMPLE_REGISTER_BYTES 12U

#endif
